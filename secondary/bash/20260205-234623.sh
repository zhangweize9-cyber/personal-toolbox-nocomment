# Git command.
# 1. Initialize file directory.
git init

# 2. Add file to buffer.
git add .

# 3. Check file status.
git status

# 4. Submit changes.
git commit -m "Test Passed!"

# 5. Add remote repository link.
git remote add origin "https://github.com/zhangweize9-cyber/personal-toolbox-nocomment.git"

# 6. Push main branch.
git push -u origin master
